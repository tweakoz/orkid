#!/usr/bin/env python3
###############################################################################
# ork.taskset.new.py — stamp a TASKSET FORMAT v1 folder at an owner-chosen path.
# Canonical spec: .claude/skills/hub-coordinator/TASKSET_FORMAT.md (this repo).
# Self-contained (stdlib only): tasksets are human-owned planning state and
# must be creatable without any engine or staging environment.
###############################################################################
import argparse, datetime, os, socket, subprocess, sys

TASKSET_MD = """# Taskset: {name}
Created: {date}
Intent: <one paragraph: what done looks like for this set of workstreams>
"""

ROSTER_MD = """# ROSTER — seat / controller / net assignments (HUMAN-EDITED)
<!-- The hub decomposes work against this file; reassignment = editing it.
     Owner runs coordinator sessions and starts WORKER nodes; coordinators
     (hub and sub) start their own controller + mailbox node unprompted.
     Defaults below = single-machine localhost; edit as the fleet grows. -->

## {host} — HUB (integration + everything, single-seat default)
- controller: tcp://localhost:7461
- nodes: {host} (localhost)
- hardware anchor: localhost
- owns epics: ALL (single-seat default — split when sub seats join)

## <sub-seat> — SUB (<role>)            <!-- template: copy per added seat -->
- controller: own (private fleet) or none
- bus link: coord-<sub-seat> restricted node on hub controller
- hardware anchor: <what is plugged in there>
- owns epics: <epic-ids>
"""

EPIC_MD = """---
id: _template
title: <outcome-level title>
priority: P2
status: open
seats: []
interacts: []
---
<outcome: what done looks like; notes>
"""

TASK_MD = """---
id: _template
epic: <epic-id>
seat: <seat>
status: todo
blockers: []
gates: <the fewest <=6min checks that prove it>
---
<what / done-when / evidence>
"""

ISSUE_MD = """---
id: _template
seat: <seat>
status: open
severity: P2
---
<what is wrong, how observed, where the evidence lives>
"""

DEVIATION_MD = """---
id: _template
date: {date}
---
<planned vs happened vs why — owner-visible honesty>
"""

GENERATED = "# {name} (generated by the hub coordinator — do not hand-edit)\n"

def main():
  ap = argparse.ArgumentParser(description="create a canonical taskset folder")
  ap.add_argument("path", help="destination folder (owner-chosen; must not exist or be empty)")
  args = ap.parse_args()
  dst = os.path.abspath(os.path.expanduser(args.path))
  if os.path.exists(dst) and os.listdir(dst):
    print("[orktaskset] FAIL: %s exists and is not empty" % dst)
    sys.exit(1)
  date = datetime.date.today().isoformat()
  name = os.path.basename(dst)
  for d in ("epics", "tasks", "completed", "issues", "deviations", "decisions", "notes"):
    os.makedirs(os.path.join(dst, d), exist_ok=True)
  writes = {
    "TASKSET.md": TASKSET_MD.format(name=name, date=date),
    "ROSTER.md": ROSTER_MD.format(host=socket.gethostname().split(".")[0].lower()),
    "epics/_template.md": EPIC_MD,
    "tasks/_template.md": TASK_MD,  # real tasks go in tasks/<epic>/<slug>.md
    "issues/_template.md": ISSUE_MD,
    "deviations/_template.md": DEVIATION_MD.format(date=date),
    "BOARD.md": GENERATED.format(name="BOARD"),
    "AWAITING_OWNER.md": GENERATED.format(name="AWAITING OWNER"),
    "decisions/.gitkeep": "", "completed/.gitkeep": "", "notes/.gitkeep": "",
    "epics/.gitkeep": "", "tasks/.gitkeep": "", "issues/.gitkeep": "",
    "deviations/.gitkeep": "",
  }
  for rel, content in writes.items():
    with open(os.path.join(dst, rel), "w") as f:
      f.write(content)
  # git init + initial commit — tasksets are owner-versioned from birth.
  # Skipped (with a note) if dst is already inside a work tree, so a taskset
  # nested in an existing planning repo does not get its own nested repo.
  def _git(*a):
    return subprocess.run(["git", "-C", dst] + list(a),
                          capture_output=True, text=True)
  inside = subprocess.run(["git", "-C", dst, "rev-parse", "--is-inside-work-tree"],
                          capture_output=True, text=True)
  if inside.returncode == 0 and inside.stdout.strip() == "true":
    git_note = "inside existing repo — no nested repo created; commit from there"
  else:
    ok = _git("init", "-q").returncode == 0 \
     and _git("add", "-A").returncode == 0 \
     and _git("commit", "-q", "-m", "taskset %s: initial skeleton (TASKSET FORMAT v1)" % name).returncode == 0
    git_note = "git repo initialized, initial commit made" if ok \
      else "git init/commit FAILED — version it manually"
  print("[orktaskset] ok new %s (epics/ tasks/ issues/ deviations/ decisions/ + ROSTER)" % dst)
  print("  git: %s" % git_note)
  print("  next: edit ROSTER.md + add epics; tell the hub: use taskset %s" % dst)

if __name__ == "__main__":
  main()
